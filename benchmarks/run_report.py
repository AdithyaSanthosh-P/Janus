"""A standalone report for one cloud voice run, generated from its archive and the CSVs.

    python benchmarks/run_report.py [--archive docs/runs/janus_fdbv3_voice_full100_2026-10-03.tgz]
                                    [--run-id cloud_20261002_182600] [--baseline cloud_20260929_232528]
                                    [--out BENCHMARK_FULL100_2026-10-03.md]

Reads the run's own reports (pass_rate_report.json, tool_calls_report.json, manifest.json,
SUMMARY.md, digest.md) from the archive, and `benchmarks/voice_recordings.csv` /
`runs.csv` for the comparison with an earlier run. No number is typed by hand. Run
`python benchmarks/collect.py` first so the CSVs contain the run.
"""

from __future__ import annotations

import argparse
import collections
import csv
import json
import os
import sys
import tarfile
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(REPO, "scripts", "fdb_v3"))
import run_digest  # noqa: E402


def _csv(name):
    with open(os.path.join(HERE, name), newline="") as fh:
        return list(csv.DictReader(fh))


def md(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def frac(v):
    """A 0-1 fraction from runs.csv as a percentage; blank stays blank."""
    try:
        return f"{100 * float(v):.1f}%"
    except (TypeError, ValueError):
        return v or ""


def pct(n, d):
    return f"{n}/{d} ({100 * n / d:.1f}%)" if d else "-"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--archive", default=os.path.join(REPO, "docs/runs/janus_fdbv3_voice_full100_2026-10-03.tgz"))
    ap.add_argument("--run-id", default="cloud_20261002_182600")
    ap.add_argument("--baseline", default="cloud_20260929_232528")
    ap.add_argument("--out", default=os.path.join(REPO, "BENCHMARK_FULL100_2026-10-03.md"))
    # Labels for a report on a later run (the defaults reproduce the 3 Oct report).
    ap.add_argument("--title", default="Full-100 voice run, judged: 3 Oct 2026")
    ap.add_argument("--label", default="3 Oct", help="short name of this run")
    ap.add_argument("--baseline-label", default="30 Sep", help="short name of the baseline run")
    ap.add_argument("--baseline-note", default="The 30 Sep run used local Whisper that fell back from the GPU to the CPU for its last quarter; this run used hosted speech-to-text.")
    ap.add_argument("--comparison-note", default="The comparison mixes the code fixes with the change from local to hosted speech-to-text.")
    ap.add_argument("--commit-note", default=" plus a fix to `scripts/fdb_v3/native_setup.sh` that does not touch the agent")
    ap.add_argument("--failure-set", default=None,
                    help="a failure_set in benchmarks/failures.csv whose causes were confirmed per recording; adds a section listing them")
    args = ap.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        with tarfile.open(args.archive) as tar:
            tar.extractall(tmp, members=[m for m in tar.getmembers() if not (m.issym() or m.islnk())])
        run = os.path.join(tmp, os.listdir(tmp)[0])
        pr = json.load(open(os.path.join(run, "pass_rate_report.json")))
        tc = json.load(open(os.path.join(run, "tool_calls_report.json")))
        man = json.load(open(os.path.join(run, "manifest.json")))
        digest = run_digest.build(__import__("pathlib").Path(run), include_passes=False)

    runs = {r["run_id"]: r for r in _csv("runs.csv")}
    voice = _csv("voice_recordings.csv")
    new = [r for r in voice if r["run_id"] == args.run_id]
    old = {(r["scenario_id"], r["speaker"]): r for r in voice if r["run_id"] == args.baseline}
    text_run = runs.get("text_text_replay_0930_final", {})
    base_run = runs.get(args.baseline + ".judged") or runs.get(args.baseline, {})
    agent = man.get("agent", {})
    metrics = tc.get("by_metric", {})

    L = []
    L += [f"# {args.title}", "",
          f"One complete FDB-v3 run (all 100 recordings, FDB's own runner and evaluators, gpt-4o judge on) of the current code through "
          f"LiveKit, on a clean cloud box. Generated by `benchmarks/run_report.py` from `docs/runs/{os.path.basename(args.archive)}` "
          f"(audio left out) and `benchmarks/voice_recordings.csv`; nothing here is typed by hand. The run is also row `{args.run_id}` "
          f"in [`BENCHMARKS.md`](BENCHMARKS.md).", ""]

    L += ["## Result", "",
          f"**{pr['passed']} of {pr['total_scenarios']} recordings pass: strict pass rate {pr['overall_pass_rate']:.1%}** (judged). "
          f"Exact-match scoring of the same run: {sum(r['exact_pass'] == '1' for r in new)}/{len(new)}.", "",
          md(["Measure", f"{args.label} (this run)", f"{args.baseline_label} full run (judged)", "Text replay, 30 Sep final (judged)", "Published best (paper, GPT-Realtime)"], [
              ["Strict pass rate (Pass@1)", f"**{pr['overall_pass_rate']:.1%}**", frac(base_run.get("pass_rate")), frac(text_run.get("pass_rate")), "60.0%"],
              ["Tool selection", metrics.get("tool_selection_acc"), base_run.get("tool_selection_acc", ""), text_run.get("tool_selection_acc", ""), "0.876"],
              ["Argument accuracy", metrics.get("argument_acc"), base_run.get("argument_acc", ""), text_run.get("argument_acc", ""), "0.680"],
              ["Response quality", metrics.get("response_qual"), base_run.get("response_quality", ""), text_run.get("response_quality", ""), "0.792"],
              ["Turn-taking", f"{tc['turn_taking']['turn_taken']}/{tc['turn_taking']['total']}", frac(base_run.get("turn_take_rate")), "n/a (text)", "-"],
              ["Mean response latency (speech end to first word)", f"{tc['latency']['avg_response_latency_s']} s (sd {tc['latency']['std_response_latency_s']}, max {tc['latency']['max_latency_s']})", f"{base_run.get('avg_response_latency_s')} s", "n/a", "paper Table 6: first-word means 3.95-8.78 s"],
          ]), ""]
    L += ["Paper figures are FDB-v3's published baselines (different hardware, models and dates; reference only). "
          + args.baseline_note, ""]

    L += ["## Breakdowns", ""]
    for title, key in (("Domain", "by_domain"), ("Difficulty", "by_difficulty"), ("Expected tool calls", "by_num_tools"), ("Disfluency feature", "by_disfluency_feature"), ("State rollback", "by_state_rollback")):
        if pr.get(key):
            L += [f"**{title}**", "", md([title, "Pass rate"], [[k, f"{v:.1%}"] for k, v in pr[key].items()]), ""]
    by_dom = collections.defaultdict(lambda: [0, 0])
    for r in new:
        by_dom[r["domain"]][1] += 1
        by_dom[r["domain"]][0] += r["judged_pass"] == "1"
    L += ["**Passes per domain (judged)**", "", md(["Domain", "Passed"], [[k, f"{v[0]}/{v[1]}"] for k, v in sorted(by_dom.items())]), ""]

    flips = collections.Counter()
    fixed, regressed = [], []
    for r in new:
        o = old.get((r["scenario_id"], r["speaker"]))
        was = "?" if o is None or o["judged_pass"] == "" else o["judged_pass"]
        flips[(was, r["judged_pass"])] += 1
        tag = f"{r['scenario_id']}/{r['speaker']}"
        if (was, r["judged_pass"]) == ("0", "1"):
            fixed.append(tag)
        if (was, r["judged_pass"]) == ("1", "0"):
            regressed.append(tag)
    L += [f"## Against the {args.baseline_label} full run, per recording (both judged, the same 100 recordings)", "",
          md([args.baseline_label, args.label, "Recordings"], [["fail", "pass (fixed)", flips[("0", "1")]], ["pass", "pass", flips[("1", "1")]],
                                                   ["fail", "fail", flips[("0", "0")]], ["pass", "fail (regressed)", flips[("1", "0")]]]), "",
          f"Regressed: {', '.join(regressed) or 'none'}. {args.comparison_note}", ""]

    unfinished = [r for r in new if r["status"] != "completed"]
    L += ["## Integrity of the run", "",
          f"- Janus commit `{man.get('janus_commit', '')[:8]}`{args.commit_note} (source digest `{str(man.get('janus_source_sha256', ''))[:16]}`); FDB commit `{man.get('fdb_commit', '')[:8]}`; judge: {man.get('judge')}.",
          f"- Agent: {agent.get('llm')} (thinking budget {agent.get('llm_thinking_budget')}, temperature {agent.get('llm_temperature')}); speech-to-text {agent.get('stt')}; TTS {agent.get('tts')}; VAD {agent.get('vad')}; end-of-turn silence {agent.get('eot_ms')} ms.",
          f"- Recordings with a status other than completed (FDB client aborts): {len(unfinished)}. Re-streamed after an abort: {len(man.get('client_abort_retries') or [])}.",
          f"- Box: RTX 3090 (24 GB), plain Ubuntu 22.04 container with no Docker, so the native path (`scripts/fdb_v3/native_setup.sh` from scratch, then `native_run.sh --judge`); Python 3.11.17, torch 2.14.0+cu126. GPU memory stayed near 6 GB.",
          "- The organizers' path is `./reproduce.sh` (Docker). Its image was rebuilt from scratch on a separate machine the same day; running that image with a GPU end to end has not been done.",
          "- One run: hosted models and FDB's mock-tool timing add run-to-run noise of a few recordings either way.", ""]

    if args.failure_set:
        confirmed = [r for r in csv.DictReader(open(os.path.join(HERE, "failures.csv"))) if r["failure_set"] == args.failure_set]
        label_classes = {"undeclared_arg", "value_type", "required_omitted", "value_not_said", "label_vs_audio", "label_wording", "conditional"}
        n_label = sum(1 for r in confirmed if r["cause_class"] in label_classes)
        counts = collections.Counter(r["cause_class"] for r in confirmed)
        L += ["## Confirmed causes", "",
              f"Each failure below was read in its decision log (set `{args.failure_set}` in `benchmarks/failures.csv`). "
              f"{n_label} of {len(confirmed)} are recordings whose label disagrees with the published tool definition, the recording, or the condition the user set "
              "(the README's [Benchmark labels](README.md#benchmark-labels-and-the-published-tools) section lists them); Janus follows the tool contract and what was said "
              "rather than fitting the label. Organizer guidance (4 Oct 2026): conforming to the open dataset's labels is not required, and such issues are to be documented.", "",
              "| Cause | Recordings |", "|---|---|"]
        L += [f"| {k} | {v} |" for k, v in counts.most_common()]
        L += ["", "| Recording | Speaker | Cause | Detail |", "|---|---|---|---|"]
        L += [f"| {r['scenario_id']} | {r['speaker']} | {r['cause_class']} | {r['cause_detail']} |" for r in confirmed]
        L += [""]

    L += [f"## Every failure ({sum(1 for r in new if r['judged_pass'] != '1')} of {len(new)})", "",
          "Generated by `scripts/fdb_v3/run_digest.py`. The cause guess is a heuristic for triage; confirm it in the decision log (in the archive) before changing code. "
          "Recordings with two speakers appear twice.", ""]
    causes = digest.split("## Failures by guessed cause", 1)[1].split("## Failing recordings", 1)[0].split("\n", 1)[1].strip()
    L += ["### By guessed cause", "", causes, "", "### Per recording", ""]
    L += [b for b in digest.split("## Failing recordings", 1)[1].strip().splitlines()]
    L += ["", "## Files", "",
          f"- `docs/runs/{os.path.basename(args.archive)}`: reports, logs, per-room decision and wire logs, `digest.md`, `manifest.json` (audio left out).",
          "- `benchmarks/voice_recordings.csv`, `benchmarks/runs.csv`, `benchmarks/failures.csv` "
          + (f"(set `{args.failure_set}`, causes confirmed)." if args.failure_set else "(set `full100_2026-10-03`, causes heuristic).")]
    with open(args.out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote", args.out, f"({len(L)} lines)")


if __name__ == "__main__":
    main()
